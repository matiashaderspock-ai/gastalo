/* Synthetic data only: review changes must never contact a real financial backup. */
const { chromium, devices } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const A = require('../app.js');
const { openDisclosure, openRowActions, openMovementFromMenu } = require('./browser-helpers.cjs');
const base = process.env.GASTALO_URL || 'http://127.0.0.1:4173/';
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  let page;
  try {
    const context = await browser.newContext({ ...devices['iPhone 13'], locale: 'es-BO', reducedMotion: 'reduce' });
    await context.route('https://api.github.com/**', route => route.abort());
    page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.clock.setFixedTime(new Date('2026-02-15T12:00:00Z'));
    await page.goto(base);
    await page.locator('.home-totals').waitFor();
    const state = A.importCSV(fs.readFileSync(__dirname + '/fixtures/coinkeeper.csv', 'utf8'), '2026-01');
    const [bank, cash] = state.accounts, category = state.categories[0];
    state.transactions = state.transactions.map(t => ({ ...t, occurred_on: '2026-02-10' }));
    state.budgets = state.budgets.filter(b => b.category_id !== category.id);
    const archived = { ...category, id: 'review-archived', name: 'Archivada', archived_at: '2026-01-01T00:00:00Z' };
    state.categories.push(archived);
    state.budgets.push({ id: 'review-limit', category_id: archived.id, month: '2026-01', limit_cents: 12345 });
    const planned = A.budgetTotals(state, '2026-02').remaining;
    A.validateState(state);
    const readState = () => page.evaluate(() => new Promise(resolve => {
      const q = indexedDB.open('gastalo'); q.onsuccess = () => {
        const db = q.result, tx = db.transaction('state');
        tx.objectStore('state').get('main').onsuccess = e => resolve(e.target.result.data);
        tx.oncomplete = () => db.close();
      };
    }));
    await page.evaluate(data => new Promise(resolve => {
      const q = indexedDB.open('gastalo'); q.onsuccess = () => {
        const db = q.result, tx = db.transaction('state', 'readwrite');
        tx.objectStore('state').put({ data, revision: 1 }, 'main');
        tx.oncomplete = () => { db.close(); resolve(); };
      };
    }), state);
    await page.reload();
    const go = async name => {
      await page.locator('#app-menu > summary').click();
      await page.getByRole('button', { name, exact: true }).click();
    };
    assert.match(await page.locator('.home-totals').innerText(), /02\/26/);
    const plannedLabel = page.locator('.home-totals .stat').filter({ has: page.getByText('Gastos planeados', { exact: true }) });
    assert.equal(await plannedLabel.count(), 1, 'The exact Gastos planeados label is retained');
    assert.equal(A.budgetTotals(await readState(), '2026-02').remaining, planned, 'Archived limits retain exactly the original financial meaning');
    for (const width of [320, 390, 1280]) {
      await page.setViewportSize({ width, height: 844 });
      await go('Historial');
      assert.equal(await page.locator('.filters').evaluate(e => e.open), false);
      assert.ok((await page.locator('.transaction').first().boundingBox()).y < 520, 'Results appear before a full phone viewport');
      assert.equal(await page.locator('.history-day h3').first().innerText(), '10/02/26');
      for (const text of await page.locator('.transaction-info > span').allTextContents()) assert.doesNotMatch(text, /\d{2}\/\d{2}\/\d{2}/);
      await openDisclosure(page, '.filters');
      assert.ok((await page.locator('#f-start').boundingBox()).height >= 44);
      await page.locator('#f-text').fill('');
      await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click();
      assert.equal(await page.locator('.filters').evaluate(e => e.open), true, 'Applying filters retains its disclosure');
      await page.locator('.filters > summary').click();
      await go('Límites de categoría');
      assert.match(await page.locator('.limit-contributions').innerText(), /Archivadas: Bs 123,45/);
      const card = page.locator('.budget-card').filter({ has: page.getByRole('heading', { name: category.name, exact: true }) });
      assert.equal(await card.locator('progress').count(), 0, 'Unlimited categories have no misleading progress bar');
      const edit = card.getByRole('button', { name: `Editar límite de ${category.name}`, exact: true });
      assert.ok((await edit.boundingBox()).height >= 44);
      await edit.click();
      await page.locator('[name="limit"]').fill('0');
      await page.getByRole('button', { name: 'Guardar', exact: true }).click();
      await page.locator('#dialog').waitFor({ state: 'hidden' });
      assert.ok(await card.evaluate(e => e.classList.contains('budget-red')));
      assert.match(await card.innerText(), /Exceso/);
      await edit.click(); await page.locator('[name="limit"]').fill('');
      await page.getByRole('button', { name: 'Guardar', exact: true }).click(); await page.locator('#dialog').waitFor({ state: 'hidden' });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await go('Inicio');
    }
    await page.locator(`[data-entity="${bank.id}"]`).click();
    const transaction = state.transactions.find(t => t.kind === 'expense' && t.from_id === bank.id);
    const editRow = page.locator(`[data-action="edit-transaction"][data-id="${transaction.id}"]`);
    await openRowActions(editRow); await editRow.click();
    const destination = await page.locator('[name="to"]').inputValue();
    await page.locator('[name="from"]').selectOption(cash.id);
    assert.equal(await page.locator('[name="to"]').inputValue(), destination, 'A valid destination survives changing the origin');
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await page.getByRole('button', { name: 'Volver a Inicio', exact: true }).click();
    await openMovementFromMenu(page);
    await page.locator('[name="from"]').selectOption(bank.id);
    await page.locator('[name="to"]').selectOption(category.id);
    await page.locator('[name="amount"]').fill('18,75');
    await page.locator('.movement-extras > summary').click();
    assert.equal(await page.locator('#movement-date-fields').isVisible(), false);
    await page.locator('#change-movement-clock').click();
    await page.locator('[name="date"]').fill('2026-02-09');
    await page.locator('[name="time"]').fill('13:25');
    await page.locator('[name="note"]').fill('Borrador de prueba');
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    assert.equal((await readState()).transactions.length, state.transactions.length, 'A draft does not become a movement');
    await page.reload(); await page.locator('.home-totals').waitFor();
    await openMovementFromMenu(page);
    await page.locator('#recover-draft').click();
    assert.equal(await page.locator('[name="amount"]').inputValue(), '18,75');
    assert.equal(await page.locator('[name="date"]').inputValue(), '2026-02-09');
    assert.equal(await page.locator('[name="to"]').inputValue(), category.id);
    await page.getByRole('button', { name: 'Registrar', exact: true }).click();
    await page.locator('#dialog').waitFor({ state: 'hidden' });
    const created = (await readState()).transactions.find(t => t.note === 'Borrador de prueba');
    assert.equal(created.occurred_on, '2026-02-09');
    assert.equal(created.occurred_time, '13:25:00');
    assert.equal(created.amount_cents, 1875);
    const beforeEdit = await readState();
    await go('Historial');
    const editCreated = page.locator(`[data-action="edit-transaction"][data-id="${created.id}"]`);
    await openRowActions(editCreated); await editCreated.click();
    await page.locator('[name="amount"]').fill('19,75');
    await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
    await page.locator('#dialog').waitFor({ state: 'hidden' });
    await page.locator('#toast [data-action="undo"]').click();
    assert.deepEqual(await readState(), beforeEdit, 'Undo restores every collection and original record after a structural-copy edit');
    await openMovementFromMenu(page);
    assert.equal(await page.locator('#recover-draft').count(), 0, 'Registering the recovered draft clears it');
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await openMovementFromMenu(page);
    await page.locator('[name="amount"]').fill('23,75');
    await page.reload(); await page.locator('.home-totals').waitFor();
    await openMovementFromMenu(page);
    await page.locator('#recover-draft').click();
    assert.equal(await page.locator('[name="amount"]').inputValue(), '23,75', 'Reloading a live form preserves its unregistered amount');
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    // Ignore and discard an old draft, then register another movement. Neither
    // path may offer the posted payload for recovery and create a duplicate.
    for (const discard of [false, true]) {
      const beforeCount = (await readState()).transactions.length;
      await openMovementFromMenu(page);
      assert.equal(await page.locator('#recover-draft').count(), 1, 'The old pending draft is present before testing ignore/discard');
      if (discard) await page.locator('#discard-draft').click();
      await page.locator('[name="from"]').selectOption(bank.id);
      await page.locator('[name="to"]').selectOption(category.id);
      await page.locator('[name="amount"]').fill(discard ? '42,25' : '31,25');
      await page.getByRole('button', { name: 'Registrar', exact: true }).click();
      await page.locator('#dialog').waitFor({ state: 'hidden' });
      assert.equal((await readState()).transactions.length, beforeCount + 1);
      await openMovementFromMenu(page);
      assert.equal(await page.locator('#recover-draft').count(), 0, 'A posted movement must never be offered as an unregistered draft');
      await page.locator('[name="amount"]').fill('29,25');
      await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    }
    await go('Gráficos');
    assert.equal(await page.locator('.filters').evaluate(e => e.open), false);
    assert.equal(await page.locator('.report-breakdown').evaluate(e => e.open), false);
    await openDisclosure(page, '.report-breakdown');
    await openDisclosure(page, '.report-breakdown .report-table');
    assert.ok(await page.locator('.report-breakdown table').isVisible());
    await go('Importar/Exportar');
    assert.equal(await page.locator('#backup-settings').evaluate(e => e.open), false);
    const before = await readState();
    await page.locator('#json-file').setInputFiles({ name: 'incorrecto.json', mimeType: 'application/json', buffer: Buffer.from('{ broken') });
    await page.getByText('Este archivo no es un respaldo JSON válido. Tus datos no se cambiaron.', { exact: true }).waitFor();
    assert.deepEqual(await readState(), before, 'A malformed file leaves all financial state untouched');
    assert.deepEqual(errors, []);
    console.log('PASS: compact history, optional filters/actions/tables, 44px controls, unchanged planned totals, budget states, valid destinations, optional dates, draft recovery/reload and safe import errors.');
  } catch (error) {
    if (page) await page.screenshot({ path: '/tmp/gastalo-review-error.png', fullPage: true });
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
